-- Pin the bootstrap to an exact commit. This clone runs before anything else,
-- so tracking the moving `stable` tag would execute unreviewed code on first
-- launch. Keep this in sync with the "lazy.nvim" entry in lazy-lock.json.
local lazy_commit = "85c7ff3711b730b4030d03144f6db6375044ae82"
local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
if not (vim.uv or vim.loop).fs_stat(lazypath) then
  local lazyrepo = "https://github.com/folke/lazy.nvim.git"
  local out = vim.fn.system({ "git", "clone", "--filter=blob:none", lazyrepo, lazypath })
  if vim.v.shell_error ~= 0 then
    vim.api.nvim_echo({
      { "Failed to clone lazy.nvim:\n", "ErrorMsg" },
      { out,                            "WarningMsg" },
      { "\nPress any key to exit..." },
    }, true, {})
    vim.fn.getchar()
    os.exit(1)
  end
  out = vim.fn.system({ "git", "-C", lazypath, "checkout", "--quiet", lazy_commit })
  if vim.v.shell_error ~= 0 then
    vim.api.nvim_echo({
      { "Failed to check out pinned lazy.nvim commit " .. lazy_commit .. ":\n", "ErrorMsg" },
      { out,                                                                    "WarningMsg" },
      { "\nPress any key to exit..." },
    }, true, {})
    vim.fn.getchar()
    os.exit(1)
  end
end
vim.opt.rtp:prepend(lazypath)

